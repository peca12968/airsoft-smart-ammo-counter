#!/usr/bin/env python3
from pathlib import Path
import json,sys,struct,zlib
root=Path(__file__).resolve().parents[1]
j=json.loads((root/'Protocol/gatt.json').read_text())
assert struct.pack('<BBHHIIIBB',1,33,300,247,53,5,2,82,0).hex()==j['goldenStateHex']
assert struct.pack('<BBHhBBB3xII',1,3,3850,100,1,1,0,1,3).hex()==j['goldenSafetyHex']
p=bytes.fromhex(j['goldenProfileHex']);assert len(p)==64 and zlib.crc32(p[:60])==struct.unpack_from('<I',p,60)[0]
values={'service':j['service'],**{k:v['uuid'] for k,v in j['characteristics'].items()}}
swift='import Foundation\n\n// Generated by scripts/generate_protocol.py from Protocol/gatt.json.\npublic enum GATT {\n    public static let version: UInt8 = %d\n'%j['version']
header='// Generated from Protocol/gatt.json. Do not edit.\n#pragma once\n#include <stdint.h>\nnamespace GATT {\nconstexpr uint8_t version = %d;\n'%j['version']
for k,v in values.items():
 swift+='    public static let %s = "%s"\n'%(k,v)
 header+='static const uint8_t %s[16] = {%s};\n'%(k,', '.join('0x%02x'%b for b in bytes.fromhex(v.replace('-',''))[::-1]))
swift+='}\n';header+='}\n'
for name,text in [('Sources/AmmoCore/GATT.swift',swift),('firmware/AmmoSensor/GATT.h',header)]:
 p=root/name
 if '--check' in sys.argv:assert p.read_text()==text,'Protocol drift: '+name
 else:p.write_text(text)
print('Protocol constants verified' if '--check' in sys.argv else 'Protocol constants generated')
